function nestStrings(strings: Record<string, string>) {
  const tree: Record<string, unknown> = {};
  for (const [path, value] of Object.entries(strings)) {
    const parts = path.split('.');
    let branch = tree;
    parts.forEach((part, index) => {
      if (index === parts.length - 1) {
        branch[part] = value;
      } else {
        const child = branch[part];
        if (!child || typeof child !== 'object') branch[part] = {};
        branch = branch[part] as Record<string, unknown>;
      }
    });
  }
  return tree;
}

export const shellTranslations = Object.fromEntries(
  Object.entries(copy).map(([locale, strings]) => [locale, { shell: nestStrings(strings) }]),
) as Record<Locale, { shell: Record<string, unknown> }>;

export const supportedShellLocales = Object.keys(shellTranslations) as Locale[];